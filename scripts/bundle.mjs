#!/usr/bin/env node
/**
 * v1.3 REFACTOR — ONE definition of "what index.js should be".
 *
 * The build and the docs gate must agree byte-for-byte, so the composition lives here and
 * both `build.mjs` and `check-docs.mjs` import it.
 *
 * Contract: index.js = HEADER + every local module in DEPENDENCY ORDER + src/index.ts,
 * each passed through Node's type stripper. Local imports are removed because the modules
 * are inlined into one scope; their `export` keywords are removed for the same reason.
 * index.ts keeps its own exports.
 *
 * Two lessons are baked in:
 *   - dependency ORDER is computed, not guessed: an inlined module that imports a later
 *     one hits a temporal-dead-zone at load, and a cycle is a hard error here;
 *   - imports are removed by a LINE walker, not a regex. A `[^}]*` regex happily spans a
 *     template literal containing the word `import` and swallows half the file — which is
 *     exactly how "Unterminated regexp literal" happened once.
 */
import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative, resolve, dirname, sep } from 'node:path'
import { stripTypeScriptTypes } from 'node:module'

export const BANNER = '// GENERATED from src/ by scripts/build.mjs — do not edit this file directly.\n'

const SPECIFIER = /from\s*['"](\.[^'"]+)['"]/u
const TERMINATES = /['"]\s*;?\s*$/u

/**
 * Remove local import statements.
 *
 * Anchored, bounded regular expressions instead of a `[\s\S]*?` scan: the loose version
 * happily ran from one `import` to a distant `} from './x.js'` and ate a template literal
 * (that is the "Unterminated regexp literal" incident). Every alternative here is limited
 * to a single line or to a bracketed block of at most 10 continuation lines.
 */
const LOCAL_SINGLE_LINE = /^import[^\n]*from[ \t]+'\.[^'\n]+';?[ \t]*\n/gmu
const LOCAL_BRACKETED = /^import[ \t]*\{\n(?:[ \t]+[^\n]*\n){0,40}?\}[ \t]*from[ \t]+'\.[^'\n]+';?[ \t]*\n/gmu
const LOCAL_SINGLE_BRACKETED = /^import[ \t]*\{(?:[^}\n]*)\}[ \t]*from[ \t]+'\.[^'\n]+';?[ \t]*\n/gmu

export function removeLocalImports(source) {
  // Normalise CRLF first: the source files are CRLF on Windows, and a regex anchored on
  // `{\n` silently matched nothing there — which is how three local imports survived into
  // the bundle and produced "Identifier 'asFiniteInteger' has already been declared".
  const normalized = source.replace(/\r\n/gu, '\n').replace(/\r/gu, '\n')
  return normalized
    .replace(LOCAL_SINGLE_LINE, '')
    .replace(LOCAL_SINGLE_BRACKETED, '')
    .replace(LOCAL_BRACKETED, '')
}

function listTsFiles(dir) {
  const out = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) out.push(...listTsFiles(full))
    else if (entry.endsWith('.ts')) out.push(full)
  }
  return out
}

function resolveSpecifier(fromFile, spec) {
  const absolute = resolve(dirname(fromFile), spec)
  return absolute.endsWith('.ts') ? absolute : `${absolute.slice(0, -'.js'.length)}.ts`
}

function localImportsOf(file) {
  const source = readFileSync(file, 'utf8')
  const targets = []
  for (const line of removeLocalImportsKeepSpecifiers(source)) targets.push(resolveSpecifier(file, line))
  return targets
}

/** Every local specifier in a file, without removing anything. */
function removeLocalImportsKeepSpecifiers(source) {
  const specs = []
  for (const match of source.matchAll(/from\s*['"](\.[^'"]+)['"]/gu)) specs.push(match[1])
  return specs
}

/**
 * Depth-first topological order over the modules REACHABLE FROM index.ts.
 *
 * Only reachable files are inlined. That is what makes a refactor safe to land in stages:
 * a brand-new module that nothing imports yet is inert, so "add the file" and "delete the
 * old block" can be separate, individually testable steps. Inlining every file under src/
 * (the first version) made any duplicate name a build failure the moment it was created.
 */
function orderModules(srcDir) {
  const indexPath = join(srcDir, 'index.ts')
  const state = new Map()
  const ordered = []
  const visit = (file, stack) => {
    if (state.get(file) === 'done') return
    if (state.get(file) === 'visiting') {
      throw new Error(`cycle in src/: ${[...stack, file].map((f) => relative(srcDir, f)).join(' -> ')}`)
    }
    state.set(file, 'visiting')
    for (const dep of localImportsOf(file)) visit(dep, [...stack, file])
    state.set(file, 'done')
    ordered.push(file)
  }
  for (const dep of localImportsOf(indexPath)) visit(dep, [indexPath])
  return ordered
}

function inline(file) {
  const source = readFileSync(file, 'utf8')
  const code = stripTypeScriptTypes(removeLocalImports(source), { mode: 'strip' })
  return code.replace(/^export\s+/gmu, '').trim()
}

/**
 * v1.3: node built-in imports are HOISTED and DEDUPED.
 *
 * Inlining two files that each `import { mkdirSync } from 'node:fs'` produced
 * "Identifier 'mkdirSync' has already been declared" — the bundle is one scope, so the
 * same specifier may appear exactly once.
 */
const NODE_IMPORT = /^import\s*\{([^}]*)\}\s*from\s*'(node:[^']+)'\s*;?[ \t]*\n?/gmu

function hoistNodeImports(pieces) {
  const byModule = new Map()
  const stripped = pieces.map((code) =>
    code.replace(NODE_IMPORT, (_whole, names, moduleName) => {
      const set = byModule.get(moduleName) ?? new Set()
      for (const name of names.split(',')) {
        const trimmed = name.trim()
        if (trimmed.length > 0) set.add(trimmed)
      }
      byModule.set(moduleName, set)
      return ''
    }),
  )
  const header = [...byModule.entries()]
    .map(([moduleName, names]) => `import { ${[...names].sort().join(', ')} } from '${moduleName}'`)
    .join('\n')
  return { header, stripped }
}

/**
 * Compose the shipped bundle for a package root.
 *
 * @param {string} root absolute package root (the directory holding `src/`)
 * @returns {{ output: string, modules: string[] }}
 */
export function composeBundle(root) {
  const srcDir = join(root, 'src')
  const ordered = orderModules(srcDir)
  const pieces = ordered.map((file) => inline(file))

  const indexSource = readFileSync(join(srcDir, 'index.ts'), 'utf8')
  pieces.push(stripTypeScriptTypes(removeLocalImports(indexSource), { mode: 'strip' }).trim())

  const names = ordered.map((file) => relative(srcDir, file).replace(/\\/gu, '/'))
  const { header: nodeHeader, stripped } = hoistNodeImports(pieces)
  const header = `${BANNER}// Inlined modules (dependency order): ${names.length === 0 ? '(none)' : names.join(', ')}\n${nodeHeader}\n`
  const output = `${header}\n${stripped.join('\n\n')}\n`

  /**
   * v1.3 GUARD: no relative specifier may survive into the shipped file.
   *
   * A single `export { x } from './core/ledger.js'` left in index.ts produced a bundle that
   * failed at IMPORT time with "Cannot find module ... core/ledger.js" — and `node --check`
   * passed, so the whole suite failing was the first symptom. Fail the BUILD instead, with
   * the offending line.
   */
  for (const [index, line] of output.split('\n').entries()) {
    if (/from\s*'\.\.?\//u.test(line)) {
      throw new Error(
        `bundle would ship an unresolved relative import (line ${index + 1}): ${line.trim()}\n` +
          'Hint: inlined modules must be re-exported BARE (`export { a, b }`), not `export ... from`.',
      )
    }
  }

  return { output, modules: names }
}
