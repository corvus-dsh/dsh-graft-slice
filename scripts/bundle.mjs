#!/usr/bin/env node
/**
 * v1.3 REFACTOR — ONE definition of "what index.js should be".
 *
 * The build and the docs gate must agree byte-for-byte, so the composition lives here and
 * both `build.mjs` and `check-docs.mjs` import it. When they each had their own copy, the
 * gate's copy is the one that silently went stale.
 *
 * Contract: index.js is HEADER + every local module (src/utils/*.ts, dependency order) +
 * src/index.ts, each passed through Node's type stripper. Local `import ... from './x.js'`
 * lines are removed because the modules are inlined into one scope; their `export`
 * keywords are removed for the same reason. index.ts keeps its own exports.
 */
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { stripTypeScriptTypes } from 'node:module'

const LOCAL_IMPORT = /^import\s*\{[^}]*\}\s*from\s*'\.\/([^']+)\.js'\s*$/gm

export const BANNER =
  '// GENERATED from src/ by scripts/build.mjs — do not edit this file directly.\n'

/**
 * Compose the shipped bundle for a package root.
 *
 * @param {string} root absolute package root (the directory holding `src/`)
 * @returns {{ output: string, modules: string[] }}
 */
export function composeBundle(root) {
  const indexSource = readFileSync(join(root, 'src', 'index.ts'), 'utf8')
  const modulePaths = []
  for (const match of indexSource.matchAll(LOCAL_IMPORT)) modulePaths.push(match[1])

  const pieces = []
  for (const relative of modulePaths) {
    const source = readFileSync(join(root, 'src', `${relative}.ts`), 'utf8')
    const code = stripTypeScriptTypes(source, { mode: 'strip' })
    pieces.push(code.replace(/^export\s+/gm, '').trim())
  }
  pieces.push(stripTypeScriptTypes(indexSource.replace(LOCAL_IMPORT, ''), { mode: 'strip' }).trim())

  const header = `${BANNER}// Inlined modules: ${modulePaths.length === 0 ? '(none)' : modulePaths.join(', ')}\n`
  return { output: `${header}\n${pieces.join('\n\n')}\n`, modules: modulePaths }
}
