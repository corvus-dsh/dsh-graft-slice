#!/usr/bin/env node
/**
 * Build index.js from src/index.ts with Node's built-in type stripper.
 *
 * This package intentionally has no build dependency: DSH loads index.js
 * directly, and Node >= 22.6 ships module.stripTypeScriptTypes(). The source
 * uses only erasable TypeScript syntax (no enums, namespaces, parameter
 * properties, or decorators).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { stripTypeScriptTypes } from 'node:module'

const sourceUrl = new URL('../src/index.ts', import.meta.url)
const targetUrl = new URL('../index.js', import.meta.url)
const source = readFileSync(sourceUrl, 'utf8')
const output = stripTypeScriptTypes(source, { mode: 'strip' })
const banner = '// GENERATED from src/index.ts by scripts/build.mjs — do not edit this file directly.\n'
writeFileSync(targetUrl, banner + output, 'utf8')
process.stdout.write(`built ${targetUrl.pathname} (${Buffer.byteLength(banner + output)} bytes)\n`)
